#!/usr/bin/env -S npx tsx
// SIG-216 — generator for path-baked badge glyphs.
//
// Reads Geist Mono Medium at 9.5px and emits SVG `<path d="..."/>` data
// for every priority + category label the badge renderer uses. The
// output module (`src/lib/badge-glyph-paths.ts`) is committed; this
// script only re-runs when the label set, the font, or the geometry
// changes.
//
// Why path-bake: Sigilix's badges used live SVG `<text>` rendered via
// the browser font pipeline, which produces softer/blurrier glyphs than
// Greptile's path-baked equivalents and depends on the viewing client
// having Geist Mono installed. Baking the geometry once, in this script,
// is the Kimi K2.6 spec for SIG-216 follow-up.
//
// Usage:
//   pnpm regenerate-badge-paths
//
// Inputs:
//   assets/fonts/GeistMono-Medium.ttf — Medium = weight 500 per spec
//
// Output:
//   src/lib/badge-glyph-paths.ts — committed TS module, machine-generated

import { readFile, writeFile } from "node:fs/promises"
import { resolve, dirname } from "node:path"
import { fileURLToPath } from "node:url"

import opentype from "opentype.js"

const HERE = dirname(fileURLToPath(import.meta.url))
const REPO_ROOT = resolve(HERE, "..")
const FONT_PATH = resolve(REPO_ROOT, "assets/fonts/GeistMono-Medium.ttf")
const OUTPUT_PATH = resolve(REPO_ROOT, "src/lib/badge-glyph-paths.ts")

// Source geometry per Kimi spec.
const FONT_SIZE = 9.5

// Badge geometry — MUST stay in sync with the constants in
// src/lib/badge-assets.ts. The renderer reads `width` / `height` from
// the generated module to position each glyph, so changing these here
// without changing them there will produce mis-centered badges.
const PRIORITY_BADGE_WIDTH = 20
const PRIORITY_BADGE_HEIGHT = 20
const CATEGORY_BADGE_HEIGHT = 20

// Category pill width formula — must match `categoryBadgeWidth` in
// src/lib/badge-assets.ts. Kept here so the generator can pre-compute
// the centering translation without importing the worker module.
function categoryBadgeWidth(label: string): number {
  return Math.ceil(label.length * 6.5 + 16)
}

const PRIORITY_LABELS = ["P0", "P1", "P2", "P3"] as const
const CATEGORY_LABELS = [
  "LOGIC",
  "SECURITY",
  "PERF",
  "ERROR",
  "TESTING",
  "COMPLEXITY",
  "STYLE",
  "SYNTAX",
  "DOCS",
] as const

interface BakedGlyph {
  readonly d: string
  readonly width: number
  readonly height: number
}

function bakeGlyph(
  font: opentype.Font,
  label: string,
  containerWidth: number,
  containerHeight: number,
): BakedGlyph {
  // Build at origin; opentype.js places the baseline at y=0 with
  // ascenders going to negative y. The path's bounding box describes
  // the inked rect.
  const path = font.getPath(label, 0, 0, FONT_SIZE)
  const bb = path.getBoundingBox()

  const glyphWidth = bb.x2 - bb.x1
  const glyphHeight = bb.y2 - bb.y1

  // Center the glyph's bounding box inside the badge rect. Use the
  // inked bb (not font cap/x-height) so all labels look optically
  // centered regardless of descender presence — none of our labels
  // have descenders, but this keeps the helper general.
  const targetCenterX = containerWidth / 2
  const targetCenterY = containerHeight / 2
  const glyphCenterX = (bb.x1 + bb.x2) / 2
  const glyphCenterY = (bb.y1 + bb.y2) / 2

  const dx = targetCenterX - glyphCenterX
  const dy = targetCenterY - glyphCenterY

  // Re-render the path with the translation baked into the coordinates
  // (rather than emitting `transform="translate(...)"`) so the rendered
  // SVG stays as a single `<path d="..."/>` element with no transform
  // arithmetic for the browser to perform per repaint.
  const translated = font.getPath(label, dx, dy, FONT_SIZE)
  const d = translated.toPathData(2) // 2 decimals — keeps bundle small without visible loss at 20px

  return {
    d,
    width: Math.round(glyphWidth * 100) / 100,
    height: Math.round(glyphHeight * 100) / 100,
  }
}

function renderModule(entries: ReadonlyArray<readonly [string, BakedGlyph]>): string {
  const header = `// Generated by scripts/generate-badge-glyph-paths.ts — DO NOT EDIT BY HAND.
//
// Path-baked SVG glyph data for every badge label rendered by
// src/lib/badge-assets.ts. Source font: Geist Mono Medium (500 weight)
// at ${FONT_SIZE}px. Each entry's \`d\` is centered for the badge's
// container geometry (20x20 for priority chips, 20-tall variable-width
// for category pills). Re-generate via:
//
//   pnpm regenerate-badge-paths

export interface BadgeGlyphPath {
  readonly d: string
  readonly width: number
  readonly height: number
}

export const BADGE_GLYPH_PATHS: Record<string, BadgeGlyphPath> = {
`

  const body = entries
    .map(([label, g]) => `  ${JSON.stringify(label)}: { d: ${JSON.stringify(g.d)}, width: ${g.width}, height: ${g.height} },`)
    .join("\n")

  const footer = `
}
`

  return `${header}${body}${footer}`
}

async function main(): Promise<void> {
  const buf = await readFile(FONT_PATH)
  // opentype.parse expects an ArrayBuffer; slice precisely to avoid
  // pulling in any prior Node Buffer padding.
  const ab = buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength)
  const font = opentype.parse(ab)

  const entries: Array<readonly [string, BakedGlyph]> = []

  for (const label of PRIORITY_LABELS) {
    entries.push([label, bakeGlyph(font, label, PRIORITY_BADGE_WIDTH, PRIORITY_BADGE_HEIGHT)])
  }

  for (const label of CATEGORY_LABELS) {
    const width = categoryBadgeWidth(label)
    entries.push([label, bakeGlyph(font, label, width, CATEGORY_BADGE_HEIGHT)])
  }

  const out = renderModule(entries)
  await writeFile(OUTPUT_PATH, out, "utf8")

  const totalBytes = entries.reduce((sum, [, g]) => sum + g.d.length, 0)
  process.stdout.write(
    `generated ${entries.length} glyphs → ${OUTPUT_PATH} (path-data total: ${totalBytes} bytes)\n`,
  )
}

main().catch((err: unknown) => {
  process.stderr.write(`generate-badge-glyph-paths failed: ${err instanceof Error ? err.stack ?? err.message : String(err)}\n`)
  process.exit(1)
})
